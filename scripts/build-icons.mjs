const root = 'packages/web/node_modules/@phosphor-icons/core/assets/light';

const paths = NAMES.map((name) => {
  const svg = readFileSync(join(root, `${name}-light.svg`), 'utf8');
  const ds = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (!ds.length || /<(?!svg|path|\/svg)/.test(svg.replace(/<path[^>]*\/>/g, ''))) {
    throw new Error(`${name}: expected only <path> elements`);
  }
  return [name, ds.join(' ')];
});

const header = (what) =>
  `// Generated by scripts/build-icons.mjs from Phosphor Icons (light), MIT licence,\n// https://phosphoricons.com. ${what} Do not edit by hand.\n`;

writeFileSync(
  'packages/shared/src/icons.ts',
  `${header('Names the display (and the brain) may use.')}
export const ICON_NAMES = ${JSON.stringify(NAMES, null, 2).replace(/"/g, "'")} as const;

export type IconName = (typeof ICON_NAMES)[number];
`,
);

writeFileSync(
  'packages/web/src/display/icon-paths.ts',
  `${header('SVG path data on a 256 × 256 grid.')}
import type { IconName } from '@ephemeralos/shared';

export const ICON_PATHS: Record<IconName, string> = {
${paths.map(([n, d]) => `  '${n}': '${d}',`).join('\n')}
};
`,
);
